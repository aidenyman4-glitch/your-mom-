ROOT = Path(__file__).resolve().parent.parent
DP = ROOT / "datapack"
RP = ROOT / "resourcepack"

errors, notes = [], []


def err(where, msg):
    errors.append(f"{where}: {msg}")


# ====================================================================== the pack on disk

def load_pack():
    funcs = {}
    for p in sorted((DP / "data").glob("*/function/**/*.mcfunction")):
        ns = p.relative_to(DP / "data").parts[0]
        rel = p.relative_to(DP / "data" / ns / "function").with_suffix("")
        funcs[f"{ns}:{rel.as_posix()}"] = p.read_text().split("\n")
    tags = {}
    for p in sorted((DP / "data").glob("*/tags/block/*.json")):
        ns = p.relative_to(DP / "data").parts[0]
        tags[f"{ns}:{p.stem}"] = json.loads(p.read_text())["values"]
    ftags = {}
    for p in sorted((DP / "data").glob("*/tags/function/*.json")):
        ns = p.relative_to(DP / "data").parts[0]
        ftags[f"{ns}:{p.stem}"] = json.loads(p.read_text())["values"]
    return funcs, tags, ftags


def _ns(i):
    return i if ":" in i else f"minecraft:{i}"


# ====================================================================== argument parsing

WORD = re.compile(r"[A-Za-z0-9_\-.+]+")
RESLOC = re.compile(r"#?[a-z0-9_.\-]+(?::[a-z0-9_.\-/]+)?")
NUMBER = re.compile(r"-?(?:\d+\.?\d*|\.\d+)")
COORD = re.compile(r"(?:[~^](?:-?(?:\d+\.?\d*|\.\d+))?|-?(?:\d+\.?\d*|\.\d+))")


def _token(s, i):
    j = i
    depth, q = 0, None
    while j < len(s):
        c = s[j]
        if q:
            if c == "\\":
                j += 2
                continue
            if c == q:
                q = None
        elif c in "\"'":
            q = c
        elif c in "[{(":
            depth += 1
        elif c in "]})":
            depth -= 1
        elif c == " " and depth == 0:
            break
        j += 1
    return j


def _balanced(s, i, open_, close):
    if i >= len(s) or s[i] != open_:
        return i
    depth, q, j = 0, None, i
    while j < len(s):
        c = s[j]
        if q:
            if c == "\\":
                j += 2
                continue
            if c == q:
                q = None
        elif c in "\"'":
            q = c
        elif c == open_:
            depth += 1
        elif c == close:
            depth -= 1
            if depth == 0:
                return j + 1
        j += 1
    return None


def parse_arg(parser, props, s, i):
    """Consume one argument of `parser` at s[i]. Returns (end, value) or None."""
    props = props or {}
    if parser == "brigadier:bool":
        m = re.compile(r"true|false").match(s, i)
        return (m.end(), m.group(0)) if m else None
    if parser in ("brigadier:integer", "brigadier:long"):
        m = re.compile(r"-?\d+").match(s, i)
        if not m:
            return None
        v = int(m.group(0))
        if "min" in props and v < props["min"] or "max" in props and v > props["max"]:
            return None
        return m.end(), v
    if parser in ("brigadier:float", "brigadier:double"):
        m = NUMBER.match(s, i)
        if not m:
            return None
        v = float(m.group(0))
        if "min" in props and v < props["min"] or "max" in props and v > props["max"]:
            return None
        return m.end(), v
    if parser == "brigadier:string":
        t = props.get("type")
        if t == "greedy":
            return len(s), s[i:]
        if t == "phrase" and i < len(s) and s[i] in "\"'":
            j = _balanced_quote(s, i)
            return (j, s[i:j]) if j else None
        m = WORD.match(s, i)
        return (m.end(), m.group(0)) if m else None
    if parser in ("minecraft:entity", "minecraft:game_profile", "minecraft:score_holder"):
        if s.startswith("@", i):
            j = i + 2
            if j < len(s) and s[j] == "[":
                j = _balanced(s, j, "[", "]")
                if j is None:
                    return None
            return j, s[i:j]
        j = _token(s, i)
        return (j, s[i:j]) if j > i else None
    if parser in ("minecraft:vec3", "minecraft:block_pos", "minecraft:vec2",
                  "minecraft:column_pos", "minecraft:rotation"):
        n = 3 if parser in ("minecraft:vec3", "minecraft:block_pos") else 2
        parts, j = [], i
        for k in range(n):
            m = COORD.fullmatch(s[j:_token(s, j)])
            if not m:
                return None
            parts.append(m.group(0))
            j = _token(s, j)
            if k < n - 1:
                if j >= len(s) or s[j] != " ":
                    return None
                j += 1
        return j, parts
    if parser in ("minecraft:block_state", "minecraft:block_predicate",
                  "minecraft:item_stack", "minecraft:item_predicate"):
        m = RESLOC.match(s, i)
        if not m:
            return None
        j = m.end()
        if j < len(s) and s[j] == "[":
            j = _balanced(s, j, "[", "]")
            if j is None:
                return None
        if j < len(s) and s[j] == "{":
            j = _balanced(s, j, "{", "}")
            if j is None:
                return None
        return j, s[i:j]
    if parser in ("minecraft:nbt_compound_tag", "minecraft:nbt_tag", "minecraft:component"):
        try:
            v, j = SNBT.parse(s[i:], partial=True)
        except SNBTError:
            return None
        if parser == "minecraft:nbt_compound_tag" and not isinstance(v, dict):
            return None
        return i + j, v
    if parser == "minecraft:nbt_path":
        j = _token(s, i)
        return (j, s[i:j]) if j > i else None
    if parser == "minecraft:message":
        return len(s), s[i:]
    if parser in ("minecraft:resource_location", "minecraft:function", "minecraft:resource",
                  "minecraft:resource_key", "minecraft:resource_or_tag", "minecraft:resource_or_tag_key",
                  "minecraft:dimension", "minecraft:loot_table", "minecraft:loot_predicate",
                  "minecraft:loot_modifier", "minecraft:resource_selector"):
        m = RESLOC.match(s, i)
        if not m or (m.end() < len(s) and s[m.end()] != " "):
            return None
        return m.end(), m.group(0)
    j = _token(s, i)
    return (j, s[i:j]) if j > i else None


def _balanced_quote(s, i):
    q, j = s[i], i + 1
    while j < len(s):
        if s[j] == "\\":
            j += 2
            continue
        if s[j] == q:
            return j + 1
        j += 1
    return None


# ====================================================================== the tree walk

class Checker:
    def __init__(self, funcs, tags, ftags):
        self.tree = MC.commands()
        self.funcs, self.tags, self.ftags = funcs, tags, ftags
        self.blocks = MC.registry("block")
        self.items = MC.registry("item")
        self.entities = MC.registry("entity_type")
        self.sounds = MC.registry("sound_event")
        sj = RP / "assets" / "sunman" / "sounds.json"
        self.pack_sounds = {f"sunman:{k}" for k in json.loads(sj.read_text())} if sj.exists() else set()
        self.objectives = set()
        for line in funcs.get("sunman:load", []):
            m = re.match(r"scoreboard objectives add (\S+) ", line)
            if m:
                self.objectives.add(m.group(1))
        self.macro_calls = {}                       # macro fn -> [(caller, provided keys or None)]
        self.called = set()

    def node(self, path):
        n = self.tree
        for p in path:
            n = n["children"][p]
        return n

    def next_children(self, node, name):
        if "redirect" in node:
            return self.node(node["redirect"]).get("children", {})
        if name == "run" and not node.get("children"):
            return self.tree["children"]
        return node.get("children", {})

    def parse(self, s):
        """Returns a list of (argname, parser, props, value) along the first full parse, or
        an error string describing the deepest failure."""
        best = [0, "nothing parsed"]

        def walk(children, i, acc):
            if i >= len(s):
                return None
            for name, ch in children.items():
                if ch["type"] == "literal":
                    if s.startswith(name, i) and (i + len(name) == len(s) or s[i + len(name)] == " "):
                        r = self._after(ch, name, i + len(name), acc + [(name, "literal", None, name)], walk, best)
                        if r is not None:
                            return r
            for name, ch in children.items():
                if ch["type"] == "argument":
                    got = parse_arg(ch.get("parser"), ch.get("properties"), s, i)
                    if got is None:
                        if i > best[0]:
                            best[:] = [i, f"cannot read <{name}> ({ch.get('parser')})"]
                        continue
                    j, v = got
                    r = self._after(ch, name, j, acc + [(name, ch.get("parser"), ch.get("properties"), v)], walk, best)
                    if r is not None:
                        return r
            if i >= best[0]:
                best[:] = [i, f"unexpected {s[i:].split(' ')[0]!r}"]
            return None

        r = walk(self.tree["children"], 0, [])
        if r is None:
            i = best[0]
            msg = best[1]
            rest = s[i:]
            if " #" in s[max(0, i - 1):] or rest.startswith("#"):
                msg += " -- a trailing `#` comment? mcfunction comments must start the line"
            return f"{msg} at column {i}: ...{s[max(0, i - 25):i]}|{rest[:40]}"
        return r

    def _after(self, ch, name, j, acc, walk, best):
        s_len = None
        if j == len(self._s):
            if ch.get("executable"):
                return acc
            if j > best[0]:
                best[:] = [j, f"incomplete command after <{name}>"]
            return None
        if self._s[j] != " ":
            if j > best[0]:
                best[:] = [j, f"unexpected text after <{name}>"]
            return None
        del s_len
        return walk(self.next_children(ch, name), j + 1, acc)

    # ------------------------------------------------------------------ semantics
    def check_line(self, where, line, macro_keys):
        if line.startswith("$"):
            keys = re.findall(r"\$\(([A-Za-z0-9_]+)\)", line)
            if not keys:
                err(where, "macro line with no $(variable)")
            sample = {"model": "sunman:blood_pool", "item": "minecraft:egg", "v": "a"}
            line = re.sub(r"\$\(([A-Za-z0-9_]+)\)", lambda m: str(sample.get(m.group(1), "1")), line[1:])
        self._s = line
        parsed = self.parse(line)
        if isinstance(parsed, str):
            err(where, parsed)
            return
        self.semantics(where, parsed)

    def semantics(self, where, parsed):
        cmd = parsed[0][3]
        path = [p[0] for p in parsed]
        for idx, (name, parser, props, val) in enumerate(parsed):
            if parser in ("minecraft:entity", "minecraft:score_holder", "minecraft:game_profile"):
                self.selector(where, val, props or {}, parser)
            elif parser == "minecraft:block_state":
                self.block(where, val, allow_tag=False)
            elif parser == "minecraft:block_predicate":
                self.block(where, val, allow_tag=True)
            elif parser in ("minecraft:item_stack", "minecraft:item_predicate"):
                iid = re.match(RESLOC, val).group(0)
                if not iid.startswith("#") and iid.split(":")[-1] not in self.items:
                    err(where, f"unknown item {iid}")
            elif parser == "minecraft:resource" and props and props.get("registry"):
                reg = props["registry"].split(":")[-1]
                if val.split(":")[-1] not in MC.registry(reg):
                    err(where, f"{val} is not in registry {reg}")
            elif parser == "minecraft:function":
                self.function_ref(where, val, parsed, idx)
            elif parser == "minecraft:objective":
                if val not in self.objectives:
                    err(where, f"objective {val} is not declared in load (OBJECTIVES)")
            elif parser == "minecraft:nbt_compound_tag" and cmd == "summon":
                ent = parsed[1][3]
                self.entity_nbt(where, ent, val)
            elif parser == "minecraft:component":
                self.text(where, val)
            elif parser in ("minecraft:vec3", "minecraft:block_pos", "minecraft:vec2", "minecraft:rotation"):
                kinds = {c[0] if c[0] in "~^" else "n" for c in val}
                if "^" in kinds and len(kinds) > 1:
                    err(where, f"cannot mix ^ with other coordinates: {' '.join(val)}")
        if cmd == "playsound":
            snd = parsed[1][3]
            if _ns(snd) not in self.pack_sounds and snd.split(":")[-1] not in self.sounds:
                err(where, f"unknown sound event {snd} (a wrong sound path is silent in game)")
        if cmd == "gamerule" and len(parsed) > 1:
            if parsed[1][3].split(":")[-1] not in MC.registry("game_rule"):
                err(where, f"unknown gamerule {parsed[1][3]}")
        del path

    def selector(self, where, val, props, parser):
        if not val.startswith("@"):
            return
        sel = parse_selector(val)
        if sel is None:
            err(where, f"bad selector {val}")
            return
        kind, args = sel
        keys = dict(args)
        single = props.get("amount") == "single"
        if single and kind in "ae" and keys.get("limit") != "1":
            err(where, f"{val}: this argument takes exactly one entity (add limit=1 or use @s/@p/@n)")
        if props.get("type") == "players" and kind in "en" and keys.get("type") != "player":
            err(where, f"{val}: only players may be selected here")
        for k, v in args:
            if k == "type" and v.lstrip("!").split(":")[-1] not in self.entities and not v.lstrip("!").startswith("#"):
                err(where, f"unknown entity type {v}")
            if k == "sort" and v not in ("nearest", "furthest", "random", "arbitrary"):
                err(where, f"bad sort {v}")
            if k not in ("type", "tag", "distance", "limit", "sort", "gamemode", "scores", "nbt", "name",
                         "x", "y", "z", "dx", "dy", "dz", "level", "team", "predicate", "advancements",
                         "x_rotation", "y_rotation"):
                err(where, f"unknown selector argument {k}")
            if k == "scores":
                for obj in re.findall(r"([A-Za-z0-9_.\-+]+)=", v):
                    if obj not in self.objectives:
                        err(where, f"objective {obj} is not declared in load")

    def tag_exists(self, name):
        name = name.lstrip("#")
        if name in self.tags:
            return True
        return name.startswith("minecraft:") and MC.tag_exists("block", name)

    def block(self, where, spec, allow_tag):
        m = re.match(r"(#?[a-z0-9_.\-:/]+)(\[[^\]]*\])?", spec)
        ident, states = m.group(1), m.group(2)
        if ident.startswith("#"):
            if not allow_tag:
                err(where, f"a tag is not allowed here: {ident}")
            elif not self.tag_exists(ident):
                err(where, f"unknown block tag {ident} (a dangling tag fails the whole pack)")
            return
        bid = ident.split(":")[-1]
        if bid not in self.blocks:
            err(where, f"unknown block {ident}")
            return
        if states:
            valid = MC.block_states(bid)
            for kv in states[1:-1].split(","):
                if not kv:
                    continue
                k, v = kv.split("=")
                if k not in valid or v not in valid[k]:
                    err(where, f"{bid} has no state {k}={v}")

    def function_ref(self, where, val, parsed, idx):
        if val.startswith("#"):
            if val[1:] not in self.ftags:
                err(where, f"unknown function tag {val}")
            return
        fid = _ns(val)
        if fid not in self.funcs:
            err(where, f"unknown function {fid}")
            return
        self.called.add(fid)
        rest = parsed[idx + 1:]
        provided = None
        if rest and rest[0][0] == "arguments":
            provided = set(rest[0][3].keys()) if isinstance(rest[0][3], dict) else set()
        elif rest and rest[0][0] == "with":
            provided = "storage"
        self.macro_calls.setdefault(fid, []).append((where, provided))

    def entity_nbt(self, where, ent, nbt):
        if ent.split(":")[-1] not in self.entities:
            return
        item = nbt.get("item") or nbt.get("Item")
        if isinstance(item, dict):
            iid = str(item.get("id", ""))
            if iid.split(":")[-1] not in self.items:
                err(where, f"unknown item {iid}")
            comps = item.get("components", {})
            model = comps.get("minecraft:item_model")
            if model:
                self.item_model(where, model)
        if "Rotation" in nbt and (not isinstance(nbt["Rotation"], list) or len(nbt["Rotation"]) != 2):
            err(where, "Rotation must be [yaw, pitch]")
        tr = nbt.get("transformation")
        if isinstance(tr, list) and len(tr) != 16:
            err(where, f"transformation matrix has {len(tr)} values, not 16")
        for k in ("CustomName", "text"):
            if isinstance(nbt.get(k), str) and nbt[k].lstrip().startswith("{"):
                err(where, f"{k} is a stringified JSON component; 26.3 takes an SNBT compound")

    def item_model(self, where, model):
        if "$(" in model or model == "sunman:blood_pool":
            pass
        ns, path = model.split(":") if ":" in model else ("minecraft", model)
        if ns == "minecraft":
            return
        p = RP / "assets" / ns / "items" / f"{path}.json"
        if not p.exists():
            err(where, f"item_model {model}: no item definition at {p.relative_to(ROOT)}")
            return
        check_item_definition(model)

    def text(self, where, val):
        if isinstance(val, str) and val.lstrip().startswith("{"):
            err(where, "text component given as a JSON string; use an SNBT compound")


# ====================================================================== resource pack

ATLAS = None


def _atlas_sources():
    global ATLAS
    if ATLAS is None:
        srcs = []
        for a in ("items", "blocks"):
            p = RP / "assets" / "minecraft" / "atlases" / f"{a}.json"
            if p.exists():
                srcs += json.loads(p.read_text())["sources"]
        ATLAS = srcs
    return ATLAS


def in_atlas(tex):
    ns, path = tex.split(":") if ":" in tex else ("minecraft", tex)
    if ns == "minecraft" and (path.startswith("item/") or path.startswith("block/")):
        return True
    for s in _atlas_sources():
        t = s["type"].split(":")[-1]
        if t == "single" and s["resource"] == f"{ns}:{path}":
            return True
        if t == "directory" and path.startswith(s["source"] + "/"):
            return True
    return False


_checked_models = set()


def check_item_definition(model_id):
    if model_id in _checked_models:
        return
    _checked_models.add(model_id)
    ns, path = model_id.split(":")
    d = json.loads((RP / "assets" / ns / "items" / f"{path}.json").read_text())
    m = d["model"].get("model")
    if not m:
        return
    mns, mpath = m.split(":")
    mp = RP / "assets" / mns / "models" / f"{mpath}.json"
    if not mp.exists():
        err(f"item {model_id}", f"model {m} missing")
        return
    model = json.loads(mp.read_text())
    for key, tex in model.get("textures", {}).items():
        if tex.startswith("#"):
            continue
        tns, tpath = tex.split(":") if ":" in tex else ("minecraft", tex)
        png = RP / "assets" / tns / "textures" / f"{tpath}.png"
        if tns != "minecraft" and not png.exists():
            err(f"model {m}", f"texture {tex} missing")
        if not in_atlas(tex):
            err(f"model {m}", f"texture {tex} is in no atlas 26.3 builds item models from "
                              "(add it to assets/minecraft/atlases/items.json)")


# ====================================================================== the run

def static():
    funcs, tags, ftags = load_pack()
    if not funcs:
        err("datapack", "no functions found -- run tools/export_datapack.py")
        return funcs, tags
    meta = json.loads((DP / "pack.mcmeta").read_text())["pack"]
    if not (meta.get("min_format", meta.get("pack_format")) <= DATA_PACK_FORMAT <= meta.get("max_format", meta.get("pack_format"))):
        err("pack.mcmeta", f"does not cover data pack format {DATA_PACK_FORMAT} (26.3)")
    rmeta = json.loads((RP / "pack.mcmeta").read_text())["pack"] if (RP / "pack.mcmeta").exists() else None
    if rmeta is None:
        err("resourcepack", "no pack.mcmeta")
    elif list(rmeta["min_format"])[0] > RESOURCE_PACK_FORMAT[0] or list(rmeta["max_format"]) < list(RESOURCE_PACK_FORMAT):
        err("resourcepack/pack.mcmeta", f"does not cover resource pack format {RESOURCE_PACK_FORMAT}")

    for name, values in tags.items():
        for v in values:
            vid = v["id"] if isinstance(v, dict) else v
            if vid.startswith("#"):
                ok = vid[1:] in tags or MC.tag_exists("block", vid[1:])
                if not ok:
                    err(f"tag #{name}", f"dangling tag reference {vid}")
            elif vid.split(":")[-1] not in MC.registry("block"):
                err(f"tag #{name}", f"unknown block {vid}")
    for name, values in ftags.items():
        for v in values:
            if _ns(v) not in funcs:
                err(f"function tag #{name}", f"unknown function {v}")

    ck = Checker(funcs, tags, ftags)
    macros = {}
    lines = 0
    for fid, body in funcs.items():
        keys = set()
        for n, line in enumerate(body, 1):
            if not line.strip() or line.startswith("#"):
                continue
            if line != line.strip():
                err(f"{fid}:{n}", "leading or trailing whitespace")
            if line.startswith("$"):
                keys |= set(re.findall(r"\$\(([A-Za-z0-9_]+)\)", line))
            ck.check_line(f"{fid}:{n}", line, keys)
            lines += 1
        if keys:
            macros[fid] = keys

    # macros: called with arguments from somewhere, and given every key they read
    for fid, keys in macros.items():
        calls = ck.macro_calls.get(fid, [])
        with_args = [c for c in calls if c[1] is not None]
        if not with_args:
            err(fid, "macro function is never called with arguments")
        for where, provided in with_args:
            if isinstance(provided, set) and not keys <= provided:
                err(where, f"calls macro {fid} without {sorted(keys - provided)}")
        for where, provided in calls:
            if provided is None:
                err(where, f"calls macro {fid} with no arguments")
    patterns = [re.compile(re.sub(r"\\\$\\\(\w+\\\)", r"\\w+", re.escape(m)) + "$")
                for body in funcs.values() for line in body if line.startswith("$")
                for m in re.findall(r"function (\S*\$\(\w+\)\S*)", line)]
    for fid in funcs:
        if any(p.match(fid) for p in patterns):
            ck.called.add(fid)
        entry = fid in ("sunman:load", "sunman:slow") or fid.startswith("sunman:world/decay_village") \
            or fid in ("sunman:fx/blood", "sunman:spawn/locust", "sunman:spawn/locust_cramped", "sunman:util/roll")
        if fid not in ck.called and not entry and fid not in [_ns(v) for vs in ftags.values() for v in vs]:
            notes.append(f"{fid} is never called")
    print(f"  static: {len(funcs)} functions, {lines} command lines parsed against the 26.3 command tree, "
          f"{len(tags)} block tags, {len(macros)} macro functions")
    return funcs, tags


