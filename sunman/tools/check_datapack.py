"""Validates the datapack against Minecraft 26.3 itself, then runs it.

    python3 tools/check_datapack.py            # static checks + the village emulation
    python3 tools/check_datapack.py --static   # static checks only

STATIC. Every command line of every function is parsed against the real 26.3 Brigadier command
tree (misode/mcmeta, generated by the game), argument by argument, and every argument is
resolved:

  * block ids and their state properties, block tags (vanilla 26.3 or the pack's own) -- a
    dangling tag fails a whole pack at load
  * entity types, item ids, sound events (vanilla, or the resource pack's sounds.json) -- a
    wrong sound id is silent, never an error, so it is checked here
  * every `minecraft:item_model` an entity carries has an item definition, a model, and
    textures that exist and sit in an atlas 26.3 builds item models from
  * functions, function tags, objectives (only those load.mcfunction declares), gamerules
  * selectors: a single-entity argument (`damage`, `tp` source...) refuses `@a`/`@e`
    without limit=1; a players-only argument refuses `@e`
  * a `#` after a command (a trailing comment) is a parse failure, and is reported as one
  * macros: every `$` line has a variable, every macro function is called with arguments
    from somewhere, and every variable it reads is one its callers provide
  * pack.mcmeta formats, tag entries

DYNAMIC. tools/village_sim.py builds a plains village from the real 26.3 structure templates
and runs the pack on it in tools/mcemu.py: load, the slow pass, the trigger, the whole
decay, a second slow pass (it must not decay twice) and the manual command (it must refuse).
Then it checks the outcome: no torch or glass or bed left, stairs that kept their facing, the
villagers gone, the counts of blood, bodies, items and Locusts the brief asks for, nothing
floating, nothing inside a wall.

Neither replaces a real server. tools/server_test.py runs one, where Mojang's servers can be
reached.
"""
